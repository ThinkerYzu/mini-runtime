"""Write glue/css_properties.js: the attribute names of Gecko's CSSStyleProperties interface
(generated in Gecko by layout/style/GenerateCSSProperties.py, gen_webidl), as release Firefox exposes
them, which depends on its prefs. Read from the browser rather than from the tree for that reason.

usage (from a Firefox source tree, under xvfb-run like the harnesses):
  STEPS=1 EVERY=0 FIREFOX_BIN=... ./mach python /path/to/bench/firefox_probe.py none \
      "data:text/html,x" /path/to/mrt-js/tools/css_properties_probe.js > OUT
  python3 tools/gen_css_properties.py OUT
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "glue", "css_properties.js")


def main():
    line = next(l for l in open(sys.argv[1]) if l.split(" ", 1)[-1].startswith('{"props"'))
    names = [n for n in json.loads(line.split(" ", 1)[1])["props"] if n != "constructor"]
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_css_properties.py from release Firefox's CSSStyleProperties.prototype.\n")
        f.write("// Do not edit. Put into prelude.js's scope at its `@CSS_PROPERTIES@` line.\n")
        f.write("const CSS_PROPERTY_ATTRIBUTES = %s;\n" % json.dumps(names, separators=(",", ":")))
    print(f"{len(names)} names to {OUT}")


if __name__ == "__main__":
    main()
