#!/usr/bin/env python3
"""Generates the HTML element interfaces of the mini runtime's bindings from Gecko's sources:

  glue/html_interfaces.h   the interfaces (HTMLAnchorElement, ...) with their parents, and the tag of
                           each HTML element to its interface (parser/htmlparser/nsHTMLTagList.inc)
  glue/html_interfaces.js  for each attribute name, the interfaces that declare it, mixins included
                           (dom/webidl/*.webidl); bridge.js puts its reflected attributes there

Usage: python3 tools/gen_html_interfaces.py [FIREFOX_TREE]   (or set FIREFOX_SRC)
Run again when the tree moves; the output is checked in.
"""
import json
import os
import re
import sys

TREE = sys.argv[1] if len(sys.argv) > 1 else os.environ["FIREFOX_SRC"]
HERE = os.path.dirname(os.path.abspath(__file__))
GLUE = os.path.join(HERE, "..", "glue")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


# ---- the tag list ----

tags = []  # (tag, interface name or None for HTMLElement)
for line in open(os.path.join(TREE, "parser/htmlparser/nsHTMLTagList.inc")):
    m = re.match(r"HTML_TAG\((\w+),\s*\w+,\s*(\w+)\)", line)
    if m:
        tags.append((m.group(1), "HTML%sElement" % m.group(2)))
        continue
    m = re.match(r"HTML_HTMLELEMENT_TAG\((\w+)\)", line)
    if m:
        tags.append((m.group(1), None))

# ---- the WebIDL: interfaces, mixins, includes ----

interfaces = {}  # name -> (parent, [attribute names])
mixins = {}  # name -> [attribute names]
includes = {}  # interface -> [mixins]
webidl = os.path.join(TREE, "dom/webidl")
for f in sorted(os.listdir(webidl)):
    if not f.endswith(".webidl"):
        continue
    text = strip_comments(open(os.path.join(webidl, f)).read())
    for m in re.finditer(r"(?:partial\s+)?interface\s+(mixin\s+)?(\w+)\s*(?::\s*(\w+))?\s*\{(.*?)\};", text, flags=re.S):
        is_mixin, name, parent, body = m.group(1), m.group(2), m.group(3), m.group(4)
        attrs = []
        # members end with ';'; an attribute's extended attributes come before it in [...]
        for member in body.split(";"):
            ext = " ".join(re.findall(r"\[(.*?)\]", member, flags=re.S))
            decl = re.sub(r"\[.*?\]", "", member, flags=re.S).strip()
            a = re.match(r"(?:stringifier\s+)?(?:readonly\s+)?(?:inherit\s+)?attribute\s+.+\s+(\w+)$", decl, flags=re.S)
            if a and "ChromeOnly" not in ext and not decl.startswith("static"):
                attrs.append(a.group(1))
        if is_mixin:
            mixins.setdefault(name, []).extend(attrs)
        else:
            old_parent, old_attrs = interfaces.get(name, (None, []))
            interfaces[name] = (parent or old_parent, old_attrs + attrs)
    for m in re.finditer(r"(\w+)\s+includes\s+(\w+)\s*;", text):
        includes.setdefault(m.group(1), []).append(m.group(2))


def own_attributes(name):
    attrs = list(interfaces.get(name, (None, []))[1])
    for mixin in includes.get(name, []):
        attrs += mixins.get(mixin, [])
    return attrs


# The interfaces the tags use, with every ancestor below HTMLElement (HTMLMediaElement), parents first.
order = []


def add(name):
    if name in order or name == "HTMLElement":
        return
    parent = interfaces.get(name, ("HTMLElement", []))[0] or "HTMLElement"
    add(parent)
    order.append(name)


for _, iface in tags:
    if iface:
        add(iface)
index = {name: i for i, name in enumerate(order)}

# ---- glue/html_interfaces.h ----

out = []
out.append("// Generated by tools/gen_html_interfaces.py from Gecko's parser/htmlparser/nsHTMLTagList.inc and")
out.append("// dom/webidl/HTML*Element.webidl. Do not edit; run the script again when the tree moves.")
out.append("")
out.append("// The HTML element interfaces below HTMLElement, parents before children.")
out.append("static const int HTML_INTERFACE_COUNT = %d;" % len(order))
out.append("static const char* const kHTMLInterfaceNames[HTML_INTERFACE_COUNT] = {")
out += ['    "%s",' % n for n in order]
out.append("};")
out.append("// The parent of each, -1 for HTMLElement.")
out.append("static const int kHTMLInterfaceParents[HTML_INTERFACE_COUNT] = {")
out += ["    %d,  // %s" % (index.get(interfaces.get(n, ("HTMLElement", []))[0] or "HTMLElement", -1), n) for n in order]
out.append("};")
out.append("// Each HTML tag's interface, -1 for HTMLElement. A tag not listed is HTMLUnknownElement, unless")
out.append("// it is a valid custom element name (HTMLElement).")
out.append("static const struct {")
out.append("  const char* tag;")
out.append("  int interface;")
out.append("} kHTMLTags[] = {")
out += ['    {"%s", %d},' % (t, index[i] if i else -1) for t, i in tags]
out.append("};")
open(os.path.join(GLUE, "html_interfaces.h"), "w").write("\n".join(out) + "\n")

# ---- glue/html_interfaces.js ----

owners = {}
for name in ["HTMLElement"] + order:
    for a in own_attributes(name):
        owners.setdefault(a, [])
        if name not in owners[a]:
            owners[a].append(name)
js = [
    "// Generated by tools/gen_html_interfaces.py from Gecko's dom/webidl. Do not edit.",
    "// For each attribute name, the HTML element interfaces that declare it (mixins included).",
    "const HTML_ATTRIBUTE_OWNERS = " + json.dumps(dict(sorted(owners.items())), separators=(",", ":")) + ";",
]
open(os.path.join(GLUE, "html_interfaces.js"), "w").write("\n".join(js) + "\n")
print(len(order), "interfaces,", len(tags), "tags,", len(owners), "attribute names")
