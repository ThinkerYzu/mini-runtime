"""Write glue/event_attribute_names.js: the event names whose `on` attribute is an event handler
content attribute for Trusted Types (TrustedTypeUtils::GetTrustedTypeDataForAttribute, which asks
nsContentUtils::IsEventAttributeName for every type but XUL's), from the Firefox tree's
dom/events/EventNameList.inc.

usage: python3 tools/gen_event_attribute_names.py [FIREFOX_TREE]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "glue", "event_attribute_names.js")


def main():
    tree = sys.argv[1] if len(sys.argv) > 1 else os.environ["FIREFOX_SRC"]
    src = open(os.path.join(tree, "dom", "events", "EventNameList.inc")).read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    names = []
    for m in re.finditer(r"^\s*[A-Z_]*EVENT\(\s*(\w+)\s*,\s*\w+\s*,\s*([^,]+?),", src, re.M):
        name, types = m.group(1), [t.strip() for t in m.group(2).split("|")]
        # EventNameType_All & ~EventNameType_XUL: a name with any type bit but XUL's
        if any(t not in ("EventNameType_XUL", "EventNameType_None") for t in types):
            names.append(name)
    names = sorted(set(names))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_event_attribute_names.py from dom/events/EventNameList.inc.\n")
        f.write("const EVENT_ATTRIBUTE_NAMES = new Set(" + repr(names).replace("'", '"') + ");\n")
    print(len(names), "names")


main()
