"""Writes glue/worker_names.js from tools/worker_names.json and tools/shared_worker_names.json: where
release Firefox puts each name of a dedicated and of a shared worker's global (DESIGN, "Workers: the
build plan"; GAPS B85), for bridge.js's worker section, which puts its members where Firefox has them
and leaves out every name Firefox's worker lacks.

worker_names.json is what bench/bridge-cases/worker-names-child.js posts in release Firefox: the
global's own names, each prototype's along its chain, WorkerNavigator's and WorkerLocation's.
shared_worker_names.json is the same from a shared worker: bench/bridge-cases/shared-worker-names.html's
log in release Firefox, less its worker script's own function `handle`.
Capture both again after a Firefox update (with firefox_probe.py, as in session 78's log).

usage: python3 tools/gen_worker_names.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
names = json.load(open(os.path.join(HERE, "worker_names.json")))
shared = json.load(open(os.path.join(HERE, "shared_worker_names.json")))
assert [n for k, n in shared.items() if k.endswith("[object WorkerGlobalScope]")] == \
    [n for k, n in names.items() if k.endswith("[object WorkerGlobalScope]")], "WorkerGlobalScope differs between the two"
proto = lambda tag: next(v for k, v in names.items() if k.endswith("[object " + tag + "]"))
out = [
    "// Generated by tools/gen_worker_names.py from release Firefox (tools/worker_names.json). Do not edit.",
    "// The own names of a dedicated worker's global.",
    "const WORKER_GLOBAL_NAMES = new Set(" + json.dumps(names["global"]) + ");",
    "// WorkerGlobalScope.prototype's members.",
    "const WORKER_GLOBAL_SCOPE_MEMBERS = " + json.dumps([n for n in proto("WorkerGlobalScope") if n != "constructor"]) + ";",
    "// WorkerNavigator's members, along its prototype chain.",
    "const WORKER_NAVIGATOR_MEMBERS = " + json.dumps([n for n in names["navigator"] if n != "constructor"]) + ";",
    "// The own names of a shared worker's global, and its WorkerNavigator's members.",
    "const SHARED_WORKER_GLOBAL_NAMES = new Set(" + json.dumps(shared["global"]) + ");",
    "const SHARED_WORKER_NAVIGATOR_MEMBERS = " + json.dumps([n for n in shared["navigator"] if n != "constructor"]) + ";",
]
open(os.path.join(HERE, "..", "glue", "worker_names.js"), "w").write("\n".join(out) + "\n")
