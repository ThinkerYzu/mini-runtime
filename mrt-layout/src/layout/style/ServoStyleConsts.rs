// Gecko: layout/base/nsPresContext.h / gfx AppUnitsPerCSSPixel() (60, the constant of nscoord).
pub const fn AppUnitsPerCSSPixel() -> i32 {
    60
}

// Gecko: layout/style/ServoStyleConstsInlines.h mozilla::detail::DefaultPercentLengthToAppUnits
fn DefaultPercentLengthToAppUnits(aPixelLength: f32) -> nscoord {
    NSToCoordTruncClamped__float(aPixelLength)
}

// Gecko: layout/style/ServoStyleConstsInlines.h mozilla::detail::DefaultLengthToAppUnits
fn DefaultLengthToAppUnits(aPixelLength: f32) -> nscoord {
    // We want to round lengths rounding 0.5 away from zero, instead of the
    // default behavior of NSToCoordRound{,WithClamp} which do floor(x + 0.5).
    let length = aPixelLength * AppUnitsPerCSSPixel() as f32;
    if length >= nscoord_MAX as f32 {
        return nscoord_MAX;
    }
    if length <= nscoord_MIN as f32 {
        return nscoord_MIN;
    }
    NSToIntRound__float(length)
}

// Gecko: layout/style/ServoStyleConstsInlines.h StyleCSSPixelLength::ToAppUnits
pub fn StyleCSSPixelLength_ToAppUnits(aLength: ComputedLength) -> nscoord {
    if aLength.px() == 0.0 {
        // Avoid the expensive FP math below.
        return 0;
    }
    DefaultLengthToAppUnits(aLength.px())
}

// Gecko: layout/style/ServoStyleConstsInlines.h LengthPercentage methods.
pub trait LengthPercentageExt {
    fn FromAppUnits(aCoord: nscoord) -> LengthPercentage;
    fn HasPercent(&self) -> bool;
    fn ConvertsToLength(&self) -> bool;
    fn ToLength(&self) -> nscoord;
    fn ConvertsToPercentage(&self) -> bool;
    fn ToPercentage(&self) -> f32;
    fn HasLengthAndPercentage(&self) -> bool;
    fn Resolve(&self, aPercentageBasis: nscoord) -> nscoord;
    fn IsDefinitelyZero(&self) -> bool;
}

impl LengthPercentageExt for LengthPercentage {
    // Gecko: layout/style/ServoStyleConstsInlines.h LengthPercentage::IsDefinitelyZero
    fn IsDefinitelyZero(&self) -> bool {
        match self.unpack() {
            Unpacked::Length(l) => l.px() == 0.0,
            Unpacked::Percentage(p) => p.0 == 0.0,
            // calc() should've been simplified to a percentage.
            Unpacked::Calc(_) => false,
        }
    }

    fn FromAppUnits(aCoord: nscoord) -> LengthPercentage {
        // FromPixels(CSSPixel::FromAppUnits(aCoord))
        LengthPercentage::new_length(ComputedLength::new(aCoord as f32 / AppUnitsPerCSSPixel() as f32))
    }

    fn HasPercent(&self) -> bool {
        // IsPercentage() || IsCalc()
        self.has_percentage()
    }

    fn ConvertsToLength(&self) -> bool {
        matches!(self.unpack(), Unpacked::Length(_))
    }

    fn ToLength(&self) -> nscoord {
        MOZ_ASSERT!(self.ConvertsToLength());
        match self.unpack() {
            Unpacked::Length(l) => StyleCSSPixelLength_ToAppUnits(l),
            _ => 0,
        }
    }

    fn ConvertsToPercentage(&self) -> bool {
        matches!(self.unpack(), Unpacked::Percentage(_))
    }

    fn ToPercentage(&self) -> f32 {
        MOZ_ASSERT!(self.ConvertsToPercentage());
        match self.unpack() {
            Unpacked::Percentage(p) => p.0,
            _ => 0.0,
        }
    }

    fn HasLengthAndPercentage(&self) -> bool {
        // IsCalc(); a calc() that is only a length or a percentage was simplified earlier.
        matches!(self.unpack(), Unpacked::Calc(_))
    }

    // Gecko: LengthPercentage::Resolve(nscoord aPercentageBasis), which uses
    // DefaultPercentLengthToAppUnits (truncation) as the rounder.
    fn Resolve(&self, aPercentageBasis: nscoord) -> nscoord {
        match self.unpack() {
            Unpacked::Length(l) => StyleCSSPixelLength_ToAppUnits(l),
            Unpacked::Percentage(p) => {
                if p.0 == 0.0 {
                    return 0;
                }
                DefaultPercentLengthToAppUnits(aPercentageBasis as f32 * p.0)
            }
            Unpacked::Calc(_) => {
                // StyleCalcLengthPercentage::Resolve: resolve in CSS pixels, then round.
                let result = self.resolve(ComputedLength::new(aPercentageBasis as f32 / AppUnitsPerCSSPixel() as f32));
                DefaultPercentLengthToAppUnits(result.px() * AppUnitsPerCSSPixel() as f32)
            }
        }
    }
}

// Gecko: layout/style/ServoStyleConstsInlines.h the methods shared by StyleSize and StyleMaxSize
// (IMPL_LENGTHPERCENTAGE_FORWARDS and IMPL_BEHAVES_LIKE_SIZE_METHODS). Layout code that is a C++
// template over `SizeOrMaxSize` is a generic function over this trait.
pub trait StyleSizeLike {
    fn IsLengthPercentage(&self) -> bool;
    fn AsLengthPercentage(&self) -> &LengthPercentage;
    fn IsFitContentFunction(&self) -> bool;
    fn AsFitContentFunction(&self) -> &LengthPercentage;
    fn IsMaxContent(&self) -> bool;
    fn IsMinContent(&self) -> bool;
    fn IsFitContent(&self) -> bool;
    fn IsStretch(&self) -> bool;
    fn IsWebkitFillAvailable(&self) -> bool;
    fn IsMozAvailable(&self) -> bool {
        false
    }
    // The keyword that is the initial value: 'auto' for StyleSize, 'none' for StyleMaxSize.
    fn BehavesLikeInitialKeyword(&self) -> bool;

    fn HasPercent(&self) -> bool {
        self.IsLengthPercentage() && self.AsLengthPercentage().HasPercent()
    }
    fn ConvertsToLength(&self) -> bool {
        self.IsLengthPercentage() && self.AsLengthPercentage().ConvertsToLength()
    }
    fn HasLengthAndPercentage(&self) -> bool {
        self.IsLengthPercentage() && self.AsLengthPercentage().HasLengthAndPercentage()
    }
    fn ToLength(&self) -> nscoord {
        MOZ_ASSERT!(self.ConvertsToLength());
        self.AsLengthPercentage().ToLength()
    }
    fn ConvertsToPercentage(&self) -> bool {
        self.IsLengthPercentage() && self.AsLengthPercentage().ConvertsToPercentage()
    }
    fn ToPercentage(&self) -> f32 {
        MOZ_ASSERT!(self.ConvertsToPercentage());
        self.AsLengthPercentage().ToPercentage()
    }

    fn BehavesLikeStretchOnInlineAxis(&self) -> bool {
        self.IsStretch() || self.IsMozAvailable() || self.IsWebkitFillAvailable()
    }
    fn BehavesLikeStretchOnBlockAxis(&self) -> bool {
        // TODO(dholbert): Add "|| IsMozAvailable()" in bug 527285.
        self.IsStretch() || self.IsWebkitFillAvailable()
    }
    fn BehavesLikeInitialValueOnBlockAxis(&self) -> bool {
        self.BehavesLikeInitialKeyword() || (!self.BehavesLikeStretchOnBlockAxis() && !self.IsLengthPercentage())
    }
    // Gecko: layout/generic/WritingModes.h StyleSize::BehavesLikeInitialValue(LogicalAxis)
    // and StyleMaxSize::BehavesLikeInitialValue(LogicalAxis)
    fn BehavesLikeInitialValue(&self, aAxis: LogicalAxis) -> bool {
        if aAxis == LogicalAxis::Inline { self.BehavesLikeInitialKeyword() } else { self.BehavesLikeInitialValueOnBlockAxis() }
    }
}

