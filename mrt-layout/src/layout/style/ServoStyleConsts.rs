// Gecko: layout/style/ServoStyleConstsInlines.h StyleCSSPixelLength::ScaleBy, ScaledBy, ToAppUnits
// (a CSS pixel length is Stylo's `computed::Length`).
pub trait StyleCSSPixelLengthExt {
    fn ScaledBy(&self, aScale: f32) -> ComputedLength;
    fn ScaleBy(&mut self, aScale: f32);
    fn ToAppUnits(&self) -> nscoord;
}
impl StyleCSSPixelLengthExt for ComputedLength {
    fn ScaledBy(&self, aScale: f32) -> ComputedLength {
        ComputedLength::new(self.px() * aScale)
    }
    fn ScaleBy(&mut self, aScale: f32) {
        *self = ComputedLength::new(self.px() * aScale);
    }
    fn ToAppUnits(&self) -> nscoord {
        StyleCSSPixelLength_ToAppUnits(*self)
    }
}

