// ADAPTER (not a translation of a whole file): the parts of layout/style/ServoStyleConsts.h and
// ServoStyleConstsInlines.h that translated layout code uses, on top of Stylo's computed value
// types (standalone `stylo`, servo configuration).
//
// In Gecko, `StyleSize`, `StyleMaxSize`, `StyleMargin`, `StyleInset` and `LengthPercentage` are
// C++ types that cbindgen generates from Stylo's Rust types, with extra inline methods
// (ServoStyleConstsInlines.h). Here the Rust types are used directly, and the extra methods are
// extension traits with Gecko's names (`HasPercent()`, `ConvertsToLength()`, `Resolve(..)`).
//
// Differences that follow from using the Rust types:
//  - `StyleSize` is `GenericSize<NonNegativeLengthPercentage>`; Gecko's cbindgen output flattens
//    the `NonNegative` wrapper away, so `AsLengthPercentage()` unwraps it here.
//  - `-moz-available` does not exist in the servo configuration (`IsMozAvailable()` is false).
//  - Gecko's `AnchorResolvedSize` (a reference-like wrapper that has resolved anchor functions) is
//    the plain Rust value here: anchor positioning is not supported, so there is nothing to resolve.
