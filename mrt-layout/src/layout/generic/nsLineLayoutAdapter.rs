// Gecko: layout/style/nsStyleStruct.h nsStyleText (the members nsLineLayout reads)
// ADAPTER: nsStyleStruct.rs's nsStyleText only has mTextAlign. This wraps the same computed style
// with the methods of nsStyleText that nsLineLayout uses, under Gecko's names. Move them into
