// ADAPTER: the per-frame stub tables, as one thread-local like the frame tree itself.
#[derive(Default)]
struct LineLayoutStubs {
    mTextFrames: HashMap<u32, TextFrameStub>,
    mReflows: HashMap<u32, FrameReflowStub>,
    // nsPlaceholderFrame::GetRealFrameForPlaceholder
    mPlaceholderFor: HashMap<u32, nsIFrame>,
    // the reverse of mPlaceholderFor (nsIFrame::GetPlaceholderFrame), so that finding the
    // placeholder of a float is not a scan over all placeholders
    mPlaceholderOf: HashMap<u32, u32>,
    // nsIFrame::IsSelfEmpty (virtual, nsInlineFrame answers from its borders/padding/margins)
    mSelfEmpty: HashMap<u32, bool>,
    mFontMetrics: Option<nsFontMetricsStub>,
}

thread_local! {
    static LINE_LAYOUT_STUBS: RefCell<LineLayoutStubs> = RefCell::new(LineLayoutStubs::default());
}

// ADAPTER: drops the per-frame side tables (stage 4; see DestroyFrameTree in driver.rs). The font
// metrics forced by a test stay.
pub fn ResetLineLayoutStubs() {
    with_stubs(|s| {
        let forced = s.mFontMetrics.take();
        *s = LineLayoutStubs::default();
        s.mFontMetrics = forced;
    });
}

// ADAPTER: drops the entries of these frames, whose slots are about to be reused (see
// ReleaseFrameSlots in driver.rs).
pub fn ReleaseLineLayoutStubs(aFrames: &[nsIFrame]) {
    with_stubs(|s| {
        for f in aFrames {
            s.mTextFrames.remove(&f.0);
            s.mReflows.remove(&f.0);
            s.mSelfEmpty.remove(&f.0);
            if let Some(oof) = s.mPlaceholderFor.remove(&f.0) {
                if s.mPlaceholderOf.get(&oof.0) == Some(&f.0) {
                    s.mPlaceholderOf.remove(&oof.0);
                }
            }
            if let Some(ph) = s.mPlaceholderOf.remove(&f.0) {
                if s.mPlaceholderFor.get(&ph).map(|x| x.0) == Some(f.0) {
                    s.mPlaceholderFor.remove(&ph);
                }
            }
        }
    });
}

fn with_stubs<R>(f: impl FnOnce(&mut LineLayoutStubs) -> R) -> R {
    LINE_LAYOUT_STUBS.with(|s| f(&mut s.borrow_mut()))
}

