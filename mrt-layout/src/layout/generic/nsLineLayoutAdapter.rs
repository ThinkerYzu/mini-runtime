impl nsLayoutUtils_LineLayoutAdapter for nsLayoutUtils {
    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::InflationMinFontSizeFor
    // NOT PORTED: font size inflation (it is off); 0 means "no inflation".
    fn InflationMinFontSizeFor(aFrame: nsIFrame) -> nscoord {
        0
    }

    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::FontSizeInflationInner
    // NOT PORTED: font size inflation; always 1.
    fn FontSizeInflationInner(aFrame: nsIFrame, aMinFontSize: nscoord) -> f32 {
        1.0
    }

    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::GetFontMetricsForFrame
    // NOT PORTED: text-combine-upright (aVariantWidth stays normal). ADAPTER: SetFontMetricsStub's
    // numbers, when set, are what comes back.
    fn GetFontMetricsForFrame(aFrame: nsIFrame, aInflation: f32) -> nsFontMetrics {
        if let Some(m) = with_stubs(|s| s.mFontMetrics) {
            return nsFontMetrics::FromStub(&aFrame.StyleFont().mFont(), m);
        }
        let computedStyle = aFrame.Style();
        let variantWidth: u8 = NS_FONT_VARIANT_WIDTH_NORMAL;
        // ADAPTER: the language of the frame's content stands in for the style's (nsStyleFont::mLanguage,
        // see nsIContent::mLanguage)
        let language = aFrame.GetContent().and_then(|c| c.mLanguage());
        nsLayoutUtils::GetFontMetricsForComputedStyleAndLanguage(&computedStyle, &aFrame.PresContext(), aInflation, variantWidth, false, language)
    }

    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::GetFontMetricsForComputedStyle
    // NOT PORTED: the font variant width (font.variantWidth; text-combine-upright), the user font
    // set, text perf metrics and feature value lookup of the pres context.
    fn GetFontMetricsForComputedStyle(
        aComputedStyle: &ServoArc<ComputedValues>,
        aPresContext: &nsPresContext,
        aInflation: f32,
        aVariantWidth: u8,
        aForceHorizontalMetrics: bool,
    ) -> nsFontMetrics {
        nsLayoutUtils::GetFontMetricsForComputedStyleAndLanguage(aComputedStyle, aPresContext, aInflation, aVariantWidth, aForceHorizontalMetrics, nsStyleFont::new(aComputedStyle.clone()).mLanguage())
    }

    // ADAPTER: GetFontMetricsForComputedStyle with the language that Gecko reads from the style (the style
    // here is shared by elements of different languages, so the caller gives it).
    fn GetFontMetricsForComputedStyleAndLanguage(
        aComputedStyle: &ServoArc<ComputedValues>,
        aPresContext: &nsPresContext,
        aInflation: f32,
        aVariantWidth: u8,
        aForceHorizontalMetrics: bool,
        aLanguage: Option<nsAtom>,
    ) -> nsFontMetrics {
        let wm = WritingMode::new__ComputedStyle(aComputedStyle);
        let styleFont = nsStyleFont::new(aComputedStyle.clone());
        let mut params = nsFontMetrics_Params::default();
        params.language = aLanguage;
        params.explicitLanguage = aLanguage.is_some();
        params.orientation = if !aForceHorizontalMetrics && wm.IsVertical() && !wm.IsSideways() {
            nsFontMetrics_FontOrientation::eVertical
        } else {
            nsFontMetrics_FontOrientation::eHorizontal
        };

        // When aInflation is 1.0 and we don't require width variant, avoid
        // making a local copy of the nsFont.
        // This also avoids running font.size through floats when it is large,
        // which would be lossy.  Fortunately, in such cases, aInflation is
        // guaranteed to be 1.0f.
        if aInflation == 1.0f32 && aVariantWidth == NS_FONT_VARIANT_WIDTH_NORMAL {
            return aPresContext.GetMetricsFor(&styleFont.mFont(), &params);
        }

        let mut font = styleFont.mFont();
        MOZ_ASSERT!(!font.size.px().is_nan(), "Style font should never be NaN");
        font.size = font.size.ScaledBy(aInflation);
        if font.size.px().is_nan() {
            font.size = ComputedLength::new(0.0);
        }
        // font.variantWidth = aVariantWidth (NOT PORTED)
        aPresContext.GetMetricsFor(&font, &params)
    }

    // Gecko: layout/base/nsLayoutUtils.h nsLayoutUtils::GetInflatedFontMetricsForFrame
    fn GetInflatedFontMetricsForFrame(aFrame: nsIFrame) -> nsFontMetrics {
        nsLayoutUtils::GetFontMetricsForFrame(aFrame, nsLayoutUtils::FontSizeInflationFor(aFrame))
    }

    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::GetCenteredFontBaseline
    fn GetCenteredFontBaseline(aFontMetrics: &nsFontMetrics, aLineHeight: nscoord, aIsInverted: bool) -> nscoord {
        let fontAscent: nscoord = if aIsInverted { aFontMetrics.MaxDescent() } else { aFontMetrics.MaxAscent() };
        let fontHeight: nscoord = aFontMetrics.MaxHeight();

        let leading: nscoord = aLineHeight - fontHeight;
        fontAscent + leading / 2
    }

    // Gecko: layout/base/nsLayoutUtils.cpp nsLayoutUtils::GetFloatFromPlaceholder
    // (the placeholder's out-of-flow frame is the one given to SetPlaceholderFor)
    fn GetFloatFromPlaceholder(aFrame: nsIFrame) -> Option<nsIFrame> {
        NS_ASSERTION!(aFrame.IsPlaceholderFrame(), "Must have a placeholder here");
        // (nsPlaceholderFrame::GetRealFrameForPlaceholder, which may be null in Gecko)
        let outOfFlowFrame = OutOfFlowFor(aFrame);
        outOfFlowFrame.filter(|f| f.IsFloating())
    }

    // Gecko: layout/base/nsLayoutUtils.h nsLayoutUtils::GetFontMetricsOfEmphasisMarks
    // NOT PORTED: text-emphasis (never set in this Stylo).
    fn GetFontMetricsOfEmphasisMarks(aFrame: nsIFrame, aInflation: f32) -> nsFontMetrics {
        nsLayoutUtils::GetFontMetricsForFrame(aFrame, aInflation)
    }
}

