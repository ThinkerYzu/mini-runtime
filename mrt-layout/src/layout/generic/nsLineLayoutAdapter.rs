    // Gecko: layout/generic/nsIFrame.h nsIFrame::IsSelfEmpty (virtual; nsInlineFrame answers from
    // its borders, padding and margins, nsBlockFrame from its margin-root status, size and
    // block-direction border and padding, nsIFrame says false). A frame answers from the stub if
    // `SetSelfEmpty` was called for it.
    // NOT PORTED: the real overrides. Nothing sets NS_BLOCK_BFC yet (the frame constructor does),
    // so a Block-typed frame cannot be told apart from an inline-block: all answer false.
    pub fn IsSelfEmpty(&self) -> bool {
        if let Some(selfEmpty) = with_stubs(|s| s.mSelfEmpty.get(&self.0).copied()) {
            return selfEmpty;
        }
        match self.Type() {
            // Inline, Line => nsInlineFrame::IsSelfEmpty
            LayoutFrameType::Inline | LayoutFrameType::Line => nsInlineFrame::from_frame(*self).IsSelfEmpty(),
            // Block => nsBlockFrame::IsSelfEmpty
            LayoutFrameType::Block => nsBlockFrame::from_frame(*self).IsSelfEmpty(),
            // Text => nsTextFrame::IsSelfEmpty
            LayoutFrameType::Text if self.UsesRealTextFrame() => nsTextFrame::from_frame(*self).IsSelfEmpty(),
            // Placeholder => nsPlaceholderFrame::IsSelfEmpty
            LayoutFrameType::Placeholder => nsPlaceholderFrame::from_frame(*self).IsSelfEmpty(),
            _ => false,
        }
    }

    // Gecko: layout/generic/nsIFrame.h nsIFrame::GetIntrinsicSize (virtual)
    // NOT PORTED: intrinsic sizes of images and other replaced frames; none has one, but video's
    // (nsVideoFrame::GetIntrinsicSize).
    pub fn GetIntrinsicSize(&self) -> IntrinsicSize {
        // Gecko: layout/svg/SVGOuterSVGFrame.cpp SVGOuterSVGFrame::GetIntrinsicSize
        // ADAPTER: the leaf block of an <svg> element (no frame class, see SVGOuterSVGFrame.rs).
        if let Some(svgData) = self.GetProperty(SVGOuterSVGDataProperty()) {
            return SVGOuterSVGFrame_GetIntrinsicSize(&svgData);
        }
        match self.Type() {
            LayoutFrameType::HTMLVideo => nsVideoFrame::from_frame(*self).GetIntrinsicSize(),
            LayoutFrameType::SubDocument => nsSubDocumentFrame::from_frame(*self).GetIntrinsicSize(),
            _ => IntrinsicSize::default(),
        }
    }

    // Gecko: layout/generic/nsBlockFrame.cpp nsBlockFrame::MarkerIsEmpty
    // ADAPTER: nsBlockFrame is not reachable from here; the body is Gecko's (style based):
    //   aMarker->StyleContent()->mContent.IsNone() ||
    //   (list->mListStyleType.IsNone() && list->mListStyleImage.IsNone() &&
    //    aMarker->StyleContent()->NonAltContentItems().IsEmpty())
    pub fn MarkerIsEmpty(&self, aMarker: nsIFrame) -> bool {
        let style = aMarker.Style();
        let contentIsNone = matches!(style.get_counters().content, mrt_style::style::values::generics::counters::Content::None);
        let typeIsNone = CounterStyleName(&style.get_list().list_style_type.0) == "none";
        let imageIsNone = matches!(style.get_list().list_style_image, mrt_style::style::values::computed::Image::None);
        contentIsNone || (typeIsNone && imageIsNone && NonAltContentItems(&style).is_empty())
    }

